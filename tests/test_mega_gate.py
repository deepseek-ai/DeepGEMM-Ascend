"""Mega Gate correctness tests and cold-L2 kernel benchmarks."""

import torch
import torch.nn.functional as F

import deep_gemm
from deep_gemm.testing import bench_msprof
from deep_gemm.testing.disable_fallback import disable_cpu_fallback
from utils import count_bytes


def calc_diff(x: torch.Tensor, y: torch.Tensor) -> float:
    # Match upstream's FP64 metric; Ascend does not support FP64 tensor arithmetic.
    x, y = x.cpu().double(), y.cpu().double()
    denominator = (x * x + y * y).sum()
    return 0.0 if denominator == 0 else (1 - 2 * (x * y).sum() / denominator).item()


def enumerate_perf_cases():
    yield from ((num_tokens, hidden, 384)
                for num_tokens in (1, 3, 16, 128, 512, 1024, 2048, 4096, 8192, 16384, 32768)
                for hidden in (4096, 5120, 7168))
    yield from (
        (512, 4096, 128), (1024, 4096, 128), (4096, 5120, 128), (32768, 7168, 128),
        (128, 4096, 256), (8192, 4352, 264), (4200, 7168, 256), (8192, 7168, 256),
        (128, 7168, 512), (8192, 4096, 512), (32768, 7168, 512),
        (32768, 4096, 512), (128, 7296, 384),
    )


def make_physical_map(num_logical_experts: int) -> tuple[torch.Tensor, torch.Tensor]:
    to_physical_map = torch.full(
        (num_logical_experts, 33), -1, dtype=torch.int32, device='npu')
    logical_count = torch.ones((num_logical_experts,), dtype=torch.int32, device='npu')
    to_physical_map[:, 0] = torch.arange(num_logical_experts, dtype=torch.int32, device='npu')
    num_duplicated_experts = min(num_logical_experts, 32)
    to_physical_map[:num_duplicated_experts, 1] = (
        num_logical_experts + torch.arange(num_duplicated_experts, dtype=torch.int32, device='npu'))
    logical_count[:num_duplicated_experts] = 2
    return to_physical_map, logical_count


def make_inputs(num_tokens: int, hidden: int, num_routed_experts: int):
    to_physical_map, logical_count = make_physical_map(num_routed_experts)
    return dict(
        x=torch.randn((num_tokens, hidden), dtype=torch.bfloat16, device='npu'),
        weight=torch.randn((num_routed_experts, hidden), dtype=torch.bfloat16, device='npu').mul_(hidden ** -0.5),
        bias=torch.randn((num_routed_experts,), dtype=torch.float32, device='npu'),
        to_physical_map=to_physical_map,
        logical_count=logical_count,
    )


def make_outputs(inputs):
    shape = (inputs['x'].shape[0], 6)
    return dict(
        topk_idx=torch.empty(shape, dtype=torch.int64, device=inputs['x'].device),
        topk_weights=torch.empty(shape, dtype=torch.float32, device=inputs['x'].device),
    )


def run_mega_gate(inputs, outputs):
    return deep_gemm.bf16_mega_gate(
        **inputs, num_topk=6, use_shared_as_routed=False, num_shared_experts=0,
        routed_scaling_factor=1.5, ep_rank=0,
        out=(outputs['topk_idx'], outputs['topk_weights']))


def run_reference_gemm(inputs) -> torch.Tensor:
    logits = torch.empty(
        (inputs['x'].shape[0], inputs['weight'].shape[0]), dtype=torch.float32, device=inputs['x'].device)
    deep_gemm.aclnn_bf16_gemm_nt(inputs['x'], inputs['weight'], logits)
    return logits


def check_correctness(outputs, logits, inputs):
    topk_idx, topk_weights = outputs['topk_idx'], outputs['topk_weights']
    num_tokens, num_experts = logits.shape
    assert topk_idx.shape == topk_weights.shape == (num_tokens, 6)
    assert (topk_idx.dtype, topk_weights.dtype) == (torch.int64, torch.float32)

    # Invert the two-copy map generated by make_physical_map.
    selected_idx = torch.where(topk_idx < num_experts, topk_idx, topk_idx - num_experts)
    assert torch.all((selected_idx >= 0) & (selected_idx < num_experts)).item()
    sorted_idx = selected_idx.sort(dim=1).values
    assert torch.all(sorted_idx[:, 1:] != sorted_idx[:, :-1]).item()

    scores = F.softplus(logits).sqrt()
    ranking = scores if inputs['bias'] is None else scores + inputs['bias']
    selected_ranking = ranking.gather(1, selected_idx).sort(dim=1, descending=True).values
    reference_ranking = ranking.topk(6, dim=1).values
    tolerance = 1e-5 + 1e-5 * ranking.abs().amax(dim=1, keepdim=True)
    ranking_error = (selected_ranking - reference_ranking).abs()
    assert torch.all(ranking_error <= tolerance).item(), f'{ranking_error.max().item()=}'

    # Tied experts may differ; normalize unbiased scores at the actual selected indices.
    selected_scores = scores.gather(1, selected_idx)
    ref_weights = selected_scores / (selected_scores.sum(dim=1, keepdim=True) + 1e-20) * 1.5
    diff = calc_diff(topk_weights, ref_weights)
    assert diff < 1e-11, f'{diff=}'

    token_idx = torch.arange(num_tokens, device=logits.device)[:, None]
    duplicate_idx = torch.fmod(token_idx * 23333, inputs['logical_count'][selected_idx])
    expected_idx = inputs['to_physical_map'][selected_idx, duplicate_idx].long()
    assert torch.equal(topk_idx, expected_idx)
    return diff


@torch.no_grad()
def test_mega_gate(skip_prof: bool = False) -> None:
    disable_cpu_fallback()
    torch.manual_seed(0)
    batch_invariance_topks = {
        (8192, 4096, 384): (6, 12, 24),
        (8192, 4352, 264): (6,),
        (128, 7296, 384): (6,),
    }
    print('Testing Mega Gate:')
    for shape in enumerate_perf_cases():
        num_tokens, hidden, num_experts = shape
        inputs = make_inputs(*shape)
        outputs = make_outputs(inputs)
        logits = run_reference_gemm(inputs)
        if shape == (128, 4096, 384):
            no_bias = dict(inputs, bias=None, mask=torch.ones(num_tokens, dtype=torch.bool, device=inputs['x'].device))
            run_mega_gate(no_bias, outputs)
            check_correctness(outputs, logits, no_bias)
        run_mega_gate(inputs, outputs)
        diff = check_correctness(outputs, logits, inputs)
        expected = {name: tensor.clone() for name, tensor in outputs.items()}
        for _ in range(10):
            run_mega_gate(inputs, outputs)
            for name, tensor in expected.items():
                assert torch.equal(outputs[name], tensor), name
        if shape in batch_invariance_topks:
            deep_gemm.use_deterministic_algorithms(True)
            for topk in batch_invariance_topks[shape]:
                args = (inputs['weight'], topk, False, 0, 1.5, 0)
                indices, weights = deep_gemm.bf16_mega_gate(inputs['x'], *args)
                small_indices, small_weights = deep_gemm.bf16_mega_gate(inputs['x'][1:4], *args)
                assert torch.equal(small_indices, indices[1:4]), f'indices: {hidden=}, {topk=}'
                assert torch.equal(small_weights.view(torch.int32), weights[1:4].view(torch.int32)), f'weights: {hidden=}, {topk=}'
            deep_gemm.use_deterministic_algorithms(False)
        if skip_prof:
            print(f' > T={num_tokens:5}, E={num_experts:3}, H={hidden:4}: diff {diff:.1e}', flush=True)
            continue
        prof = bench_msprof(lambda: run_mega_gate(inputs, outputs), kernel_names='mega_gate')
        flops = 2.0 * num_tokens * num_experts * hidden
        logical_bytes = count_bytes(*inputs.values(), *outputs.values())
        print(f' > T={num_tokens:5}, E={num_experts:3}, H={hidden:4}: {prof.dur_us:6.1f} us, '
              f'{prof.tflops(flops):4.0f} TFLOPS, {prof.gbps(logical_bytes):4.0f} GB/s | '
              f'AIC[mte2={prof.aic_mte2 * 100:4.1f}%, mad={prof.aic_mad * 100:4.1f}%] | '
              f'AIV[mte2={prof.aiv_mte2 * 100:4.1f}%, vec={prof.aiv_vec * 100:4.1f}%] | '
              f'diff {diff:.1e}', flush=True)
    print()


if __name__ == '__main__':
    test_mega_gate()
